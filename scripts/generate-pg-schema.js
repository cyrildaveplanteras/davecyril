require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') });
const fs = require('fs');
const path = require('path');

const dump = require('./mysql-schema-dump.json');

const TYPE_MAP = {
  'int': 'INTEGER',
  'bigint': 'BIGINT',
  'tinyint': 'SMALLINT',
  'smallint': 'SMALLINT',
  'mediumint': 'INTEGER',
  'varchar': 'VARCHAR',
  'char': 'CHAR',
  'text': 'TEXT',
  'tinytext': 'TEXT',
  'mediumtext': 'TEXT',
  'longtext': 'TEXT',
  'decimal': 'NUMERIC',
  'numeric': 'NUMERIC',
  'float': 'REAL',
  'double': 'DOUBLE PRECISION',
  'date': 'DATE',
  'datetime': 'TIMESTAMP',
  'timestamp': 'TIMESTAMP',
  'time': 'TIME',
  'blob': 'BYTEA',
  'mediumblob': 'BYTEA',
  'longblob': 'BYTEA',
  'json': 'JSONB',
};

function quoteIdent(name) {
  return /[A-Z\s]/.test(name) ? `"${name}"` : name;
}

function pgType(col) {
  const dt = col.dataType;
  if (!TYPE_MAP[dt]) throw new Error(`Unmapped type ${dt} for ${col.table}.${col.name}`);
  let t = TYPE_MAP[dt];
  if ((dt === 'varchar' || dt === 'char') && col.maxLen) t += `(${col.maxLen})`;
  if ((dt === 'decimal' || dt === 'numeric') && col.numPrec != null) {
    t += `(${col.numPrec}${col.numScale != null ? ',' + col.numScale : ''})`;
  }
  return t;
}

function pgDefault(col) {
  const d = col.default;
  if (d === null || d === undefined) return null;
  let s = String(d);
  if (s.toLowerCase() === 'null') return null;
  if (/current_timestamp\(\)/i.test(s)) return 'CURRENT_TIMESTAMP';
  if (col.dataType === 'datetime' || col.dataType === 'timestamp' || col.dataType === 'date') {
    if (/^\d{4}-\d{2}-\d{2}/.test(s)) return `'${s}'`;
    return null;
  }
  if (['int', 'bigint', 'tinyint', 'smallint', 'mediumint', 'decimal', 'numeric', 'float', 'double'].includes(col.dataType)) {
    return s.replace(/'/g, '').replace(/\s+/g, '');
  }
  // String types: strip MySQL's surrounding quotes, then escape and re-quote.
  if (s.startsWith("'") && s.endsWith("'") && s.length >= 2) s = s.slice(1, -1);
  return `'${s.replace(/'/g, "''")}'`;
}

function buildCreateTable(tableName) {
  const cols = dump.columns.filter(c => c.table === tableName).sort((a, b) => a.ordinal - b.ordinal);
  const colDefs = cols.map((c) => {
    let def = `  ${quoteIdent(c.name)} ${pgType(c)}`;
    const isPk = c.key === 'PRI';
    if (!c.nullable && !isPk) def += ' NOT NULL';
    if (/auto_increment/.test(c.extra)) {
      def += ' GENERATED BY DEFAULT AS IDENTITY';
      if (isPk) def += ' PRIMARY KEY';
    } else {
      const d = pgDefault(c);
      if (d !== null) def += ` DEFAULT ${d}`;
      if (isPk) def += ' PRIMARY KEY';
    }
    return def;
  });
  return `CREATE TABLE IF NOT EXISTS ${quoteIdent(tableName)} (\n${colDefs.join(',\n')}\n)`;
}

function buildIndexes(tableName) {
  const indexes = new Map();
  for (const idx of dump.indexes.filter(i => i.table === tableName && i.name !== 'PRIMARY')) {
    if (!indexes.has(idx.name)) indexes.set(idx.name, { unique: idx.unique, columns: [] });
    indexes.get(idx.name).columns.push(quoteIdent(idx.column));
  }
  const stmts = [];
  for (const [name, idx] of indexes) {
    stmts.push(`CREATE ${idx.unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${name.replace(/[^a-zA-Z0-9_]/g, '_')} ON ${quoteIdent(tableName)} (${idx.columns.join(', ')})`);
  }
  return stmts;
}

function buildForeignKeys(tableName) {
  const stmts = [];
  for (const fk of dump.foreignKeys.filter(f => f.table === tableName)) {
    stmts.push(
      `DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${fk.name}') THEN ALTER TABLE ${quoteIdent(fk.table)} ADD CONSTRAINT ${fk.name} FOREIGN KEY (${quoteIdent(fk.column)}) REFERENCES ${quoteIdent(fk.refTable)} (${quoteIdent(fk.refColumn)}); END IF; END $$;`
    );
  }
  return stmts;
}

function hasColumn(tableName, colName) {
  return dump.columns.some(c => c.table === tableName && c.name === colName);
}

const allStmts = [];
const tables = dump.tables.map(t => t.name);

for (const t of tables) {
  allStmts.push(buildCreateTable(t));
  allStmts.push(...buildIndexes(t));
}
for (const t of tables) {
  allStmts.push(...buildForeignKeys(t));
}

// UpdatedAt triggers (parity with MySQL ON UPDATE CURRENT_TIMESTAMP)
const triggerFn = `
CREATE OR REPLACE FUNCTION set_updated_at_upper() RETURNS trigger AS $$
BEGIN
  NEW."UpdatedAt" = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION set_updated_at_lower() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
`;
allStmts.push(triggerFn);

for (const t of tables) {
  if (hasColumn(t, 'UpdatedAt')) {
    allStmts.push(`DROP TRIGGER IF EXISTS trg_${t}_updated ON ${quoteIdent(t)}`);
    allStmts.push(`CREATE TRIGGER trg_${t}_updated BEFORE UPDATE ON ${quoteIdent(t)} FOR EACH ROW EXECUTE FUNCTION set_updated_at_upper()`);
  }
  if (hasColumn(t, 'updated_at')) {
    allStmts.push(`DROP TRIGGER IF EXISTS trg_${t}_updated_lower ON ${quoteIdent(t)}`);
    allStmts.push(`CREATE TRIGGER trg_${t}_updated_lower BEFORE UPDATE ON ${quoteIdent(t)} FOR EACH ROW EXECUTE FUNCTION set_updated_at_lower()`);
  }
}

const moduleBody = `// AUTO-GENERATED from scripts/mysql-schema-dump.json by scripts/generate-pg-schema.js
// PostgreSQL schema for GoldenHope (mirrors the MySQL production schema exactly,
// preserving mixed-case column names so the renderer keeps working unchanged).

const SCHEMA_STATEMENTS = ${JSON.stringify(allStmts, null, 2)};

const TRIGGER_STATEMENTS = [${JSON.stringify(triggerFn)}];

async function applySchema(pool) {
  for (const stmt of SCHEMA_STATEMENTS) {
    await pool.execute(stmt);
  }
}

module.exports = { applySchema, SCHEMA_STATEMENTS, TRIGGER_STATEMENTS };
`;

const outPath = path.join(__dirname, '..', 'src', 'js', 'pg-schema.js');
fs.writeFileSync(outPath, moduleBody);
console.log(`Generated ${outPath}`);
console.log(`  ${allStmts.length} statements (${tables.length} tables + indexes + FKs + triggers)`);